double f8(double a,double b,double c,double d,double e,double f,double g,double h){
  return a+b*2+c*3+d*4+e*5+f*6+g*7+h*8;
}
double mix(long n, double a, double b, double c, double d, double e, double f, double g){
  return n*1000 + a+b*2+c*3+d*4+e*5+f*6+g*7;
}
double f6(double a,double b,double c,double d,double e,double f){ return a+b*2+c*3+d*4+e*5+f*6; }
long ganz8(long a,long b,long c,long d,long e,long f,long g,long h){ return a+b*2+c*3+d*4+e*5+f*6+g*7+h*8; }
